#!/bin/bash
# Resumable driver.  Re-run this script after any restart: finished chunks are skipped.
# Needs: python3, git with push access to the remote of this checkout.
# Results are written to a scratch directory outside the git checkout (so the checkout is only
# ever dirty for the instant of a checkpoint) and copied in at each checkpoint.
REPO="$(cd "$(dirname "$0")" && pwd)"
WORK="${WORK:-$HOME/z4-run}"
mkdir -p "$WORK"
cp -n "$REPO"/results_n*_d*.jsonl "$WORK"/ 2>/dev/null   # seed from the last checkpoint (resume)
cp "$REPO"/fibre_check.py "$WORK"/
cd "$WORK"
JOBS="5:5 4:5 4:6 6:5 5:6 7:5 4:7 5:7 6:6 8:5 7:6 5:8"
WORKERS=${WORKERS:-3}
status() {
python3 - <<'PY'
import json,glob,time,os
rows=[]
for f in sorted(glob.glob("results_n*_d*.jsonl")):
    recs=[json.loads(l) for l in open(f) if l.strip()]
    ch=[r for r in recs if isinstance(r.get("chunk"),int)]
    end=[r for r in recs if r.get("chunk")=="END"]
    if not ch: continue
    bad=[b for r in ch for b in r["disconnected"]]
    rows.append((ch[0]["n"],ch[0]["d"],len(ch),end[0]["chunks"] if end else None,sum(r["margins"] for r in ch),max(r["max_fibre"] for r in ch),len(bad)))
out=["# Z/4 fibre-connectivity search: status","",f"Updated {time.strftime('%Y-%m-%d %H:%M UTC',time.gmtime())}. Generated by run_all.sh; do not edit.","",
"A disconnected fibre in degree d means a minimal generator of degree d. Degrees up to 4 are expected; any in degree above 4 is a counterexample to the bound for Z/4.","",
"| leaves n | degree d | chunks done | total chunks | margins checked | largest fibre | disconnected fibres |","|---|---|---|---|---|---|---|"]
for n,d,c,t,m,mx,b in sorted(rows):
    out.append(f"| {n} | {d} | {c} | {t if t is not None else 'running'} | {m} | {mx} | {b}{' **COUNTEREXAMPLE**' if b and d>4 else ''} |")
open("STATUS.md","w").write("\n".join(out)+"\n")
PY
}
pusher() {
  while true; do
    sleep ${PUSH_EVERY:-300}
    checkpoint
  done
}
checkpoint() {
    status
    cp results_n*_d*.jsonl STATUS.md run.log "$REPO"/ 2>/dev/null
    cd "$REPO"
    git add -A . >/dev/null 2>&1
    if ! git diff --cached --quiet; then
      git -c user.name="michaellady" -c user.email="michaellady@users.noreply.github.com" commit -q -m "Z/4 search: checkpoint $(date -u +%FT%TZ)" -m "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" -m "Claude-Session: https://claude.ai/code/session_018BGgP71Mo4NpS11fqeLnVJ" && git push -q origin HEAD 2>>"$WORK"/push.err
    fi
    cd "$WORK"
}
pusher & PUSHER=$!
trap "kill $PUSHER 2>/dev/null" EXIT
echo "$JOBS" | tr ' ' '\n' | xargs -P "$WORKERS" -I{} sh -c 'n=$(echo {} | cut -d: -f1); d=$(echo {} | cut -d: -f2); if grep -q "\"END\"" results_n${n}_d${d}.jsonl 2>/dev/null; then echo "n=$n d=$d already complete"; else python3 fibre_check.py $n $d 200; fi' >> run.log 2>&1
checkpoint
