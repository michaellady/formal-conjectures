#!/usr/bin/env python3
"""Generate a self-contained Lean 4 (Mathlib) proof that the Sturmfels-Sullivant degree bound fails
for Z/m on three leaves, from a two-table counterexample.  usage: gen_counterexample.py data.json out.lean"""
import json, sys, collections
d=json.load(open(sys.argv[1])); m=d["modulus"]
cnt=lambda T: collections.Counter({tuple(r):k for r,k in T})
A,B=cnt(d["A"]),cnt(d["B"]); deg=sum(A.values()); assert deg==sum(B.values()) and deg>m
col=lambda C,i: collections.Counter(x for r,k in C.items() for x in [r[i]]*k)
need=[col(A,i) for i in range(3)]
T=sorted((a,b) for a in need[0] for b in need[1] if (-a-b)%m in need[2])
third=lambda p:(-p[0]-p[1])%m
al=[A.get((a,b,third((a,b))),0) for a,b in T]; be=[B.get((a,b,third((a,b))),0) for a,b in T]
assert sum(al)==deg and sum(be)==deg
piv=next(i for i in range(len(T)) if al[i]==0 and be[i]==1)
N=len(T); ns=f"Z{m}"
ms=lambda c:"{"+", ".join(f"({a}, {b})" for (a,b),k in zip(T,c) for _ in range(k))+"}"
cols=[lambda p:p[0],lambda p:p[1],third]; gn=["Prod.fst","Prod.snd","thd"]; hs=["h1","h2","h3"]
eqs=[(j,v,[i for i,p in enumerate(T) if cols[j](p)==v],need[j][v]) for j in range(3) for v in sorted(need[j])]
L=[f'''/-
# The Sturmfels–Sullivant degree bound fails for ℤ/{m} (machine-checked)

`SturmfelsSullivant.not_generatedInDegree_zmod{m}`: the ideal of the group-based model for `ℤ/{m}` on
the claw tree `K_{{1,3}}` is NOT generated in degree `≤ {m}` (combinatorial form of Michałek,
arXiv:1508.04177, Section 2).  There are two compatible tables of {deg} flows with no common row
whose compatibility class consists of exactly those two tables.

Proof: every row of a compatible table is one of {N} admissible types (finite check); the column
conditions give {len(eqs)} linear equations in the {N} multiplicities, which force the multiplicity
vector of one of the two tables (linear integer arithmetic); the tables share no row, so no
exchange of at most {m} rows connects them.  Generated by `gen_counterexample.py`.
-/
import Mathlib

namespace {ns}

abbrev K := ZMod {m} × ZMod {m}

/-- Third entry of the flow encoded by a pair. -/
def thd (p : K) : ZMod {m} := -p.1 - p.2

/-- The {N} admissible row types. -/
def T : List K := [{", ".join(f"({a}, {b})" for a,b in T)}]

/-- Table `A` ({deg} rows). -/
def PA : Multiset K := {ms(al)}

/-- Table `B` ({deg} rows). -/
def PB : Multiset K := {ms(be)}

lemma T_nodup : T.Nodup := by decide

lemma count_map_eq_sum {{γ : Type*}} [DecidableEq γ] (P : Multiset K) (hP : ∀ p ∈ P, p ∈ T)
    (g : K → γ) (v : γ) :
    (P.map g).count v = (T.map fun t => if g t = v then P.count t else 0).sum := by
  rw [Multiset.count_map, ← Multiset.toFinset_sum_count_eq, ← List.sum_toFinset _ T_nodup]
  rw [Finset.sum_subset (s₂ := T.toFinset)]
  · refine Finset.sum_congr rfl fun t _ => ?_
    rw [Multiset.count_filter]
    by_cases h : g t = v
    · simp [h]
    · have : ¬ v = g t := fun e => h e.symm
      simp [h, this]
  · intro t ht
    rw [Multiset.mem_toFinset, Multiset.mem_filter] at ht
    exact List.mem_toFinset.mpr (hP t ht.1)
  · intro t _ ht
    rw [Multiset.mem_toFinset] at ht
    exact Multiset.count_eq_zero_of_notMem ht

set_option maxRecDepth 10000 in
lemma PA_sub : ∀ p ∈ PA, p ∈ T := by decide

set_option maxRecDepth 10000 in
lemma PB_sub : ∀ p ∈ PB, p ∈ T := by decide

set_option maxRecDepth 10000 in
lemma mem_T_of_cols : ∀ a ∈ (PA.map Prod.fst), ∀ b ∈ (PA.map Prod.snd),
    (-a - b : ZMod {m}) ∈ PA.map thd → ((a, b) : K) ∈ T := by decide

set_option maxHeartbeats 4000000 in
theorem fibre_eq (P : Multiset K) (h1 : P.map Prod.fst = PA.map Prod.fst)
    (h2 : P.map Prod.snd = PA.map Prod.snd) (h3 : P.map thd = PA.map thd) :
    P = PA ∨ P = PB := by
  have hP : ∀ p ∈ P, p ∈ T := by
    rintro ⟨a, b⟩ hp
    refine mem_T_of_cols a ?_ b ?_ ?_
    · rw [← h1]; exact Multiset.mem_map_of_mem Prod.fst hp
    · rw [← h2]; exact Multiset.mem_map_of_mem Prod.snd hp
    · rw [← h3]; exact Multiset.mem_map_of_mem thd hp''']
for n_,(j,v,idx,c) in enumerate(eqs):
    lhs=" + ".join(f"P.count (({T[i][0]}, {T[i][1]}) : K)" for i in idx)
    L.append(f'''  have e{n_} : {lhs} = {c} := by
    have h := count_map_eq_sum P hP {gn[j]} ({v} : ZMod {m})
    rw [{hs[j]}] at h
    have hc : (PA.map {gn[j]}).count ({v} : ZMod {m}) = {c} := by decide
    rw [hc] at h
    simp (config := {{ decide := true }}) [T] at h
    omega''')
for i,(a,b) in enumerate(T): L.append(f"  generalize hx{i} : P.count (({a}, {b}) : K) = x{i} at *")
for i in range(N):
    if i==piv: continue
    k=al[i]-be[i]
    if k>=0: L.append(f"  have r{i} : x{i} + {k} * x{piv} = {al[i]} := by omega")
    else: L.append(f"  have r{i} : x{i} = {al[i]} + {-k} * x{piv} := by omega")
L.append("  clear "+" ".join(f"e{j}" for j in range(len(eqs))))
L.append(f"  have hx : x{piv} = 0 ∨ x{piv} = 1 := by omega")
def branch(c,tgt):
    s=[f"    have v{i} : x{i} = {c[i]} := by omega" for i in range(N)]
    s+=["    refine Multiset.ext.mpr fun t => ?_","    by_cases ht : t ∈ T",
        "    · simp only [T, List.mem_cons, List.not_mem_nil, or_false] at ht",
        "      rcases ht with "+" | ".join(["rfl"]*N)]
    s+=[f"      · rw [hx{i}, v{i}]; decide" for i in range(N)]
    s+=[f"    · have hPT := {tgt}_sub","      rw [Multiset.count_eq_zero_of_notMem fun h => ht (hP t h),",
        "        Multiset.count_eq_zero_of_notMem fun h => ht (hPT t h)]"]
    return "\n".join(s)
L.append("  rcases hx with h0 | h1'"); L.append("  · left\n"+branch(al,"PA")); L.append("  · right\n"+branch(be,"PB"))
firstA=next((a,b) for (a,b),k in zip(T,al) if k>0)
L.append(f'''
end {ns}

namespace SturmfelsSullivant

variable (n : ℕ) (G : Type*) [AddCommGroup G]

/-- A group-based flow on `n` leaves. -/
def Flow : Type _ := {{f : Fin n → G // ∑ i, f i = 0}}

variable {{n G}}

/-- Compatible multisets of flows: same entries at every leaf. -/
def Compatible (M₁ M₂ : Multiset (Flow n G)) : Prop :=
  ∀ i : Fin n, M₁.map (fun f => f.1 i) = M₂.map (fun f => f.1 i)

/-- Exchange a sub-multiset `A` of at most `d` flows by a compatible multiset `B`. -/
def Step (d : ℕ) (M M' : Multiset (Flow n G)) : Prop :=
  ∃ A B C : Multiset (Flow n G), M = A + C ∧ M' = B + C ∧ A.card ≤ d ∧ B.card ≤ d ∧
    Compatible A B

variable (n G) in
/-- Generated in degree `≤ d`, combinatorial form. -/
def GeneratedInDegree (d : ℕ) : Prop :=
  ∀ M₁ M₂ : Multiset (Flow n G), Compatible M₁ M₂ → Relation.ReflTransGen (Step d) M₁ M₂

lemma Step.compatible {{d : ℕ}} {{M M' : Multiset (Flow n G)}} (h : Step d M M') :
    Compatible M M' := by
  obtain ⟨A, B, C, rfl, rfl, -, -, hAB⟩ := h
  intro i
  rw [Multiset.map_add, Multiset.map_add, hAB i]

open {ns}

def pr (f : Flow 3 (ZMod {m})) : K := (f.1 0, f.1 1)

def toFlow (p : K) : Flow 3 (ZMod {m}) :=
  ⟨![p.1, p.2, thd p], by simp [Fin.sum_univ_three, thd]⟩

lemma pr_toFlow (p : K) : pr (toFlow p) = p := rfl

lemma thd_pr (f : Flow 3 (ZMod {m})) : thd (pr f) = f.1 2 := by
  have h := f.2
  rw [Fin.sum_univ_three] at h
  simp only [thd, pr]
  linear_combination (-1 : ZMod {m}) * h

lemma toFlow_pr (f : Flow 3 (ZMod {m})) : toFlow (pr f) = f := by
  apply Subtype.ext
  funext i
  fin_cases i
  · rfl
  · rfl
  · exact thd_pr f

def A : Multiset (Flow 3 (ZMod {m})) := PA.map toFlow
def B : Multiset (Flow 3 (ZMod {m})) := PB.map toFlow

lemma map_toFlow_col (P : Multiset K) :
    (P.map toFlow).map (fun f => f.1 0) = P.map Prod.fst ∧
    (P.map toFlow).map (fun f => f.1 1) = P.map Prod.snd ∧
    (P.map toFlow).map (fun f => f.1 2) = P.map thd := by
  refine ⟨?_, ?_, ?_⟩ <;> rw [Multiset.map_map] <;> rfl

lemma map_pr_col (M : Multiset (Flow 3 (ZMod {m}))) :
    (M.map pr).map Prod.fst = M.map (fun f => f.1 0) ∧
    (M.map pr).map Prod.snd = M.map (fun f => f.1 1) ∧
    (M.map pr).map thd = M.map (fun f => f.1 2) := by
  refine ⟨?_, ?_, ?_⟩
  · rw [Multiset.map_map]; rfl
  · rw [Multiset.map_map]; rfl
  · rw [Multiset.map_map]; exact Multiset.map_congr rfl fun f _ => thd_pr f

lemma map_toFlow_map_pr (M : Multiset (Flow 3 (ZMod {m}))) : (M.map pr).map toFlow = M := by
  rw [Multiset.map_map]
  conv_rhs => rw [← Multiset.map_id M]
  exact Multiset.map_congr rfl fun f _ => toFlow_pr f

/-- The compatibility class of `A` is `{{A, B}}`. -/
theorem eq_A_or_B_of_compatible (M : Multiset (Flow 3 (ZMod {m}))) (h : Compatible A M) :
    M = A ∨ M = B := by
  obtain ⟨a0, a1, a2⟩ := map_toFlow_col PA
  obtain ⟨m0, m1, m2⟩ := map_pr_col M
  have h1 : (M.map pr).map Prod.fst = PA.map Prod.fst := by rw [m0, ← a0]; exact (h 0).symm
  have h2 : (M.map pr).map Prod.snd = PA.map Prod.snd := by rw [m1, ← a1]; exact (h 1).symm
  have h3 : (M.map pr).map thd = PA.map thd := by rw [m2, ← a2]; exact (h 2).symm
  rcases fibre_eq _ h1 h2 h3 with e | e
  · left; rw [← map_toFlow_map_pr M, e]; rfl
  · right; rw [← map_toFlow_map_pr M, e]; rfl

set_option maxRecDepth 10000 in
lemma cols_eq : PA.map Prod.fst = PB.map Prod.fst ∧ PA.map Prod.snd = PB.map Prod.snd ∧
    PA.map thd = PB.map thd := by decide

lemma A_B_compatible : Compatible A B := by
  obtain ⟨a0, a1, a2⟩ := map_toFlow_col PA
  obtain ⟨b0, b1, b2⟩ := map_toFlow_col PB
  obtain ⟨c0, c1, c2⟩ := cols_eq
  intro i
  fin_cases i
  · exact a0.trans (c0.trans b0.symm)
  · exact a1.trans (c1.trans b1.symm)
  · exact a2.trans (c2.trans b2.symm)

set_option maxRecDepth 10000 in
lemma PA_PB_disjoint : ∀ p ∈ PA, p ∉ PB := by decide

set_option maxRecDepth 10000 in
lemma card_PA : PA.card = {deg} := by decide

lemma A_ne_B : A ≠ B := by
  intro h
  have : PA = PB := by
    have h' := congrArg (Multiset.map pr) h
    simpa [A, B, Multiset.map_map, Function.comp_def, pr_toFlow] using h'
  have hmem : (({firstA[0]}, {firstA[1]}) : K) ∈ PA := by decide
  exact PA_PB_disjoint _ hmem (this ▸ hmem)

/-- From `A`, no exchange of at most {deg-1} flows leads anywhere else. -/
lemma step_A {{M' : Multiset (Flow 3 (ZMod {m}))}} (h : Step {deg-1} A M') : M' = A := by
  have hc := h.compatible
  obtain ⟨A', B', C, hA, hM, hcard, -, -⟩ := h
  rcases eq_A_or_B_of_compatible M' hc with e | e
  · exact e
  · exfalso
    have hcardA : A.card = {deg} := by rw [A, Multiset.card_map, card_PA]
    have hC : C ≠ 0 := by
      rintro rfl
      rw [hA, add_zero] at hcardA
      omega
    obtain ⟨c, hcC⟩ := Multiset.exists_mem_of_ne_zero hC
    have hcA : c ∈ A := by rw [hA]; exact Multiset.mem_add.mpr (Or.inr hcC)
    have hcB : c ∈ B := by rw [← e, hM]; exact Multiset.mem_add.mpr (Or.inr hcC)
    obtain ⟨p, hp, rfl⟩ := Multiset.mem_map.mp hcA
    obtain ⟨q, hq, hqp⟩ := Multiset.mem_map.mp hcB
    have : q = p := by simpa [pr_toFlow] using congrArg pr hqp
    exact PA_PB_disjoint p hp (this ▸ hq)

/-- On three leaves the ideal for `ℤ/{m}` is not generated in degree `≤ {deg-1}`. -/
theorem not_generatedInDegree_zmod{m}_sharp : ¬ GeneratedInDegree 3 (ZMod {m}) {deg-1} := by
  intro h
  have hreach := h A B A_B_compatible
  have hstay : ∀ M, Relation.ReflTransGen (Step {deg-1}) A M → M = A := by
    intro M hM
    induction hM with
    | refl => rfl
    | tail _ hs ih => rw [ih] at hs; exact step_A hs
  exact A_ne_B (hstay _ hreach).symm

lemma GeneratedInDegree.mono {{d e : ℕ}} (hde : d ≤ e) (h : GeneratedInDegree n G d) :
    GeneratedInDegree n G e := by
  intro M₁ M₂ hc
  have hr := h M₁ M₂ hc
  clear hc
  induction hr with
  | refl => exact Relation.ReflTransGen.refl
  | tail _ hs ih =>
    obtain ⟨A, B, C, h1, h2, h3, h4, h5⟩ := hs
    exact ih.tail ⟨A, B, C, h1, h2, h3.trans hde, h4.trans hde, h5⟩

/-- **The Sturmfels–Sullivant degree bound fails for `ℤ/{m}`**: on three leaves the ideal of the
group-based model is not generated in degree `≤ {m}`. -/
theorem not_generatedInDegree_zmod{m} : ¬ GeneratedInDegree 3 (ZMod {m}) {m} :=
  fun h => not_generatedInDegree_zmod{m}_sharp (h.mono (by norm_num))

end SturmfelsSullivant

#print axioms SturmfelsSullivant.not_generatedInDegree_zmod{m}
#print axioms SturmfelsSullivant.not_generatedInDegree_zmod{m}_sharp
''')
open(sys.argv[2],"w").write("\n".join(L))
print(f"m={m} degree={deg} types={N} equations={len(eqs)} pivot=x{piv}")
